// Confirm modal
const Confirm = {
  show(msg, onYes) {
    const box = document.getElementById('modal-box');
    box.innerHTML = `
      <div class="p-6 text-center">
        <div class="w-12 h-12 bg-red-100 rounded-full flex items-center justify-center mx-auto mb-4">
          <svg class="w-6 h-6 text-red-600" fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-3L13.732 4c-.77-1.333-2.694-1.333-3.464 0L3.34 16c-.77 1.333.192 3 1.732 3z"/>
          </svg>
        </div>
        <p class="text-sm font-semibold text-gray-900 mb-1">Confirmar exclusão</p>
        <p class="text-sm text-gray-500 mb-6">${msg}</p>
        <div class="flex gap-3">
          <button onclick="Modal.close()" class="flex-1 py-2.5 border border-gray-200 text-gray-700 rounded-xl text-sm font-semibold hover:bg-gray-50">
            Cancelar
          </button>
          <button onclick="Confirm._confirm()" class="flex-1 py-2.5 bg-red-600 text-white rounded-xl text-sm font-semibold hover:bg-red-700">
            Excluir
          </button>
        </div>
      </div>
    `;
    this._cb = onYes;
    Modal.open();
  },
  _cb: null,
  _confirm() { Modal.close(); if (this._cb) this._cb(); },
};

const Modal = {
  open() {
    const overlay = document.getElementById('modal-overlay');
    overlay.classList.remove('hidden');
    document.body.style.overflow = 'hidden';
  },
  close() {
    document.getElementById('modal-overlay').classList.add('hidden');
    document.body.style.overflow = '';
  },
  closeOnOverlay(e) {
    if (e.target === document.getElementById('modal-overlay')) this.close();
  },
};
